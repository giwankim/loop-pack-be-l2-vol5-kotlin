package com.loopers.application.brand.required

/**
 * 브랜드 삭제가 상품 조각에 시키는 것. 브랜드를 삭제하면 그 브랜드의 삭제되지 않은 상품도 함께 삭제된다(CONTEXT.md 브랜드, ADR 0017).
 *
 * 시키는 쪽인 브랜드가 모양을 선언하고 상품 조각의 Service가 직접 구현한다. 그래서 브랜드는 상품을 참조하지 않고,
 * 의존은 도메인에서처럼 상품에서 브랜드로만 간다. 부르는 쪽의 트랜잭션에 참여하므로 브랜드와 상품의 삭제는 함께 커밋되고 함께 되돌아간다.
 */
interface ProductDeleter {
    /**
     * [brandId] 브랜드의 삭제되지 않은 상품을 모두 삭제한다. 재고가 0인 상품도 삭제하고, 이미 삭제된 상품의 삭제 시각은 그대로 둔다.
     * 상품 행을 id 오름차순으로 잠가 읽은 뒤 하나씩 삭제한다(ADR 0018).
     *
     * 부른 뒤에도 삭제된 상품은 영속성 컨텍스트에 남는다. 삭제 필터는 SQL에만 붙으므로 같은 트랜잭션에서
     * `EntityManager.find`로 그 상품을 다시 찾으면 삭제된 인스턴스가 돌아온다.
     */
    fun deleteAllOfBrand(brandId: Long)
}
