package com.loopers.application.product.provided

/**
 * 결제에 실패한 주문의 재고 예약을 돌려준다(ADR 0026 규칙 3). 상품의 재고는 상품 조각만 바꾼다.
 * 확정과 대사의 TX B가 주문을 잠근 뒤 부르고, 그 트랜잭션에 참여한다. 그래서 돌려주기는 결제의 실패와 함께 커밋되고 함께 되돌아간다.
 */
interface StockRestorer {
    /**
     * [quantities]의 상품마다 그 수량을 재고에 더한다. 키는 상품 ID이고 값은 돌려줄 수량이다. 관리자가 그 사이 재고를 맞췄어도 그 위에 더한다
     * (ADR 0026 규칙 5).
     *
     * 없거나 삭제된 상품은 건너뛰고 나머지에 돌려준다. 돌려준 수량이 삭제된 상품을 되살리지 않는다(ADR 0026 규칙 4). 삭제는 예약을 기다리지 않으므로
     * 결제 중에 삭제된 상품은 정상이고, [StockDeductor]처럼 거절하지 않는다.
     *
     * 상품 행은 이 돌려주기가 처음 읽으면서 id 오름차순으로 잠근다(ADR 0018). 같은 트랜잭션에서 잠그지 않고 먼저 읽어 둔 상품이면 낡은 재고에
     * 더하므로, 부르는 쪽은 그 상품들을 미리 읽지 않는다.
     */
    fun restore(quantities: Map<Long, Int>)
}
