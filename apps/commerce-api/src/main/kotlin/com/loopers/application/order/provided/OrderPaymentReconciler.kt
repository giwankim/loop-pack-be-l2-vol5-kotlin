package com.loopers.application.order.provided

/**
 * PG의 대사(대사하다). PG가 알림으로 PG 거래가 바뀌었다고 알리면, 결제의 웹 어댑터가 그 PG 주문 번호의 결제를 찾아 결제의 주문으로 이 포트를
 * 부른다(ADR 0031 규칙 3). 고객의 [OrderConfirmer.reconcile]과 같은 PG 주문 번호 조회와 같은 TX B로 대사한다.
 *
 * 고객의 대사와 구현은 같지만 부르는 쪽이 달라 포트를 따로 둔다(ADR 0013). 요청자는 웹 경계의 헤더에서만 오므로(ADR 0015), PG를 고객인 척
 * 부르지 않는다. 결제를 PG 주문 번호로 찾은 것이 소유 확인을 대신한다.
 */
interface OrderPaymentReconciler {
    /**
     * 주문 [orderId]의 결제를 대사한다. 끝나지 않은 결제를 PG 주문 번호로 조회해, 찾은 PG 거래를 고객의 대사와 같은 경계로 반영한다. PG에 돌려줄
     * 주문 정보가 없으므로 아무것도 돌려주지 않는다.
     *
     * - 결제 중인 주문만 PG에 조회한다. 찾은 PG 거래로 결제가 성공으로 끝나면 주문은 확정된 주문, 실패로 끝나면 결제에 실패한 주문이 되고
     *   예약을 돌려준다. 같은 답을 확정, 고객의 대사, 다른 알림이 함께 반영해도 주문은 한 번만 바뀐다.
     * - PG 거래를 찾지 못했거나, PG 거래가 여럿이거나 결제와 맞지 않으면 결제와 예약은 그대로 두고 돌아간다. 대사는 끝났다.
     * - 조회할 수 없으면 결제와 예약을 그대로 두고 `PG_UNAVAILABLE`을 던진다. 묻지 못했으므로 다시 받으면 답이 바뀔 수 있다. 고객의 대사가
     *   저장된 상태로 답하는 것과 다른 하나다(ADR 0031 규칙 6).
     * - 포인트로 확정된 주문과 결제가 끝난 주문은 PG에 조회하지 않고 돌아간다.
     * - 없는 주문은 `ORDER_NOT_FOUND`이고, 확정 전 주문은 대사할 결제가 없어 `PAYMENT_NOT_STARTED`다.
     * - 트랜잭션 안에서 부르면 `IllegalTransactionStateException`이다. PG 조회가 트랜잭션에 들지 않게 막는다(ADR 0028 규칙 2).
     */
    fun reconcile(orderId: Long)
}
