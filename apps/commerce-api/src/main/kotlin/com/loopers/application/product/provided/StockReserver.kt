package com.loopers.application.product.provided

/**
 * 결제 중인 주문의 재고 예약(ADR 0026). 주문 확정의 TX A가 예약하고, 결제에 실패한 주문의 TX B가 돌려준다. 예약은 재고에서 미리 빼 두는
 * 것이고, 결제가 성공하면 예약을 소비할 뿐 재고를 더 줄이지 않으므로 부를 것이 없다. 상품의 재고는 상품 슬라이스만 바꾼다.
 * 두 쪽 모두 부르는 쪽의 트랜잭션에 참여하므로 예약은 결제의 시작과, 돌려주기는 결제의 실패와 함께 커밋되고 함께 되돌아간다(ADR 0024 규칙 1).
 *
 * 예약과 돌려주기는 유스케이스가 다르지만 포트 하나에 둔다. 구현도, 부르는 조율 서비스도, 부르는 쪽의 트랜잭션에 참여한다는 조건도 같다.
 *
 * 상품 행은 두 쪽 모두 처음 읽으면서 id 오름차순으로 잠근다(ADR 0018). 같은 트랜잭션에서 잠그지 않고 먼저 읽어 둔 상품이면 Hibernate가
 * 처음 읽은 필드 값을 그대로 두어 낡은 재고에서 빼거나 더하므로, 부르는 쪽은 그 상품들을 미리 읽지 않는다.
 */
interface StockReserver {
    /**
     * [quantities]의 상품마다 그 수량만큼 재고를 예약한다. 키는 상품 ID이고 값은 예약할 수량이다. 주문 확정의 TX A가 부른다.
     * 상품을 모두 읽은 뒤에야 재고를 빼므로, 하나라도 없거나 삭제됐으면 어느 재고도 줄이지 않고 `PRODUCT_NOT_FOUND`를 던진다.
     * 그래서 없는 상품이 재고 부족보다 앞서고, 그 차례는 키의 차례와 무관하다(포인트·주문 설계 15).
     * 재고가 모자란 상품이 있으면 [com.loopers.domain.product.InsufficientStockException]을 던지고, 앞서 뺀 재고는 부르는 쪽의 트랜잭션이 되돌린다.
     */
    fun reserve(quantities: Map<Long, Int>)

    /**
     * [quantities]의 상품마다 그 수량을 재고에 돌려준다. 키는 상품 ID이고 값은 돌려줄 수량이다. 확정과 대사의 TX B가 주문을 잠근 뒤
     * 결제에 실패한 주문에만 부른다(ADR 0026 규칙 3). 관리자가 그 사이 재고를 맞췄어도 그 위에 더한다(ADR 0026 규칙 5).
     *
     * 없거나 삭제된 상품은 건너뛰고 나머지에 돌려준다. 돌려준 수량이 삭제된 상품을 되살리지 않는다(ADR 0026 규칙 4). 삭제는 예약을 기다리지 않으므로
     * 결제 중에 삭제된 상품은 정상이고, [reserve]처럼 거절하지 않는다.
     */
    fun release(quantities: Map<Long, Int>)
}
